#!/usr/bin/env python3
"""Generate the reference chapters of the manual from the code, and the printable book.

    python tools/build_manual.py              # write 4.1, 4.2 and 4.3
    python tools/build_manual.py --check      # exit 1 if any of them is out of date
    python tools/build_manual.py --book       # also write build/bace-manual.html

4.1 is read from the parameter specs of every module (`service/modules.py`),
4.2 from the check catalogue (`service/pipeline.py` `CHECK_DOCS`) and the
per-shot verdicts (`service/wire.py` `SHOT_CHECKS`), 4.3 from the bench
actions (`service/rigs.py` `ACTION_DOCS`). A change to any of them is a
change to the code, and `tests/test_manual.py` fails until the chapters are
written again.

The book is every chapter of `docs/manual/` in order, as one HTML file with a
contents page and a print stylesheet, for printing or PDF export from a
browser. It converts the subset of Markdown the manual uses: headings to
level 3, paragraphs, tables, flat bulleted or numbered lists, fenced and
space-indented code blocks, inline code, emphasis, links, and figures: a line
holding only `![caption](img/name.png)`, whose image is embedded in the book
so that it stays one file. Anything else
comes out as text; keep the manual to that subset.
"""
from __future__ import annotations

import argparse
import base64
import html
import mimetypes
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

MANUAL = os.path.join(ROOT, "docs", "manual")
BOOK = os.path.join(ROOT, "build", "bace-manual.html")
GENERATED_NOTE = ("Generated by `tools/build_manual.py` from {source}. Do not edit by hand: "
                  "change the code and run the tool again.")


# -- the generated chapters -----------------------------------------------------------
def _cell(text: str) -> str:
    """One table cell: on one line, with its pipes escaped."""
    return " ".join(str(text).split()).replace("|", "\\|")


def _value(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, float):
        return f"`{value:g}`"
    if isinstance(value, (tuple, list)):
        return "`[" + ", ".join(f"{v:g}" if isinstance(v, float) else str(v) for v in value) + "]`"
    if isinstance(value, str):
        return f'`"{value}"`' if value else '`""`'
    return f"`{value}`"


def _limits(spec) -> str:
    if spec.choices:
        return ", ".join(f"`{c}`" for c in spec.choices)
    lo, hi = spec.minimum, spec.maximum
    if lo is not None and hi is not None:
        return f"{lo:g} to {hi:g}"
    if lo is not None:
        return f"≥ {lo:g}"
    if hi is not None:
        return f"≤ {hi:g}"
    return ""


def parameters() -> str:
    from bace.experiment.rig import RigConfig
    from bace.service.modules import MODULE_NAMES, Catalogue, recipe_keys

    cat = Catalogue(rig_config=RigConfig())
    out = ["# Parameters", "",
           "Every parameter of every module: its default in the code, unit, limits and "
           "meaning, and the `run.toml` key that sets it. A value from `run.toml`, the "
           "last run or an edit overrides the default (3.1). Rig-dependent defaults are "
           "those of a `rig.toml` with no entries.", "",
           GENERATED_NOTE.format(source="the parameter specs in `bace/service/modules.py`"),
           ""]
    for name in MODULE_NAMES:
        spec = cat.spec(name)
        params = cat.param_specs(name)
        keys = recipe_keys(name)
        out += [f"## {name}", ""]
        if not params:
            out += [f"`{name}` has no parameters.", ""]
            continue
        out += [f"Kind: {spec.kind}.", "",
                "| Parameter | Default | Unit | Limits | run.toml | Meaning |",
                "|---|---|---|---|---|---|"]
        for p in params:
            recipe = ", ".join(f"`{k}`" for k in keys.get(p.name, []))
            out.append("| " + " | ".join(_cell(c) for c in (
                f"`{p.name}`", _value(p.default), p.unit, _limits(p), recipe, p.doc)) + " |")
        out.append("")
    return "\n".join(out)


def checks() -> str:
    from bace.service.pipeline import CHECK_DOCS
    from bace.service.plans import PLAN_CHECK
    from bace.service.wire import SHOT_CHECKS

    out = ["# Checks and warnings", "",
           "Every check the bench makes, the condition it reports and the remedy. "
           "A message in the console states its own evidence; this chapter states "
           "the rule.", "",
           GENERATED_NOTE.format(source="`CHECK_DOCS` in `bace/service/pipeline.py` and "
                                        "`SHOT_CHECKS` in `bace/service/wire.py`"),
           "",
           "## Before a run", "",
           "The Dry run and Start run every check below, in this order, on the whole "
           "pipeline; Start runs them again against a fresh read-back. A check at "
           "`crit` or `invalid` refuses the run; `warn` and `info` do not. The level "
           "given is the most severe the check reports.", "",
           "| Check | Level | Reported when | Remedy |",
           "|---|---|---|---|"]
    for code, (level, when, remedy) in CHECK_DOCS.items():
        out.append("| " + " | ".join(_cell(c) for c in (
            f"`{code}`", f"`{level}`", when, remedy)) + " |")
    code, level, when, remedy = PLAN_CHECK
    out += ["", "## Under a plan", "",
            "A run submitted under an approved plan is also checked against the "
            "plan's envelope (`service/plans.py`).", "",
            "| Check | Level | Reported when | Remedy |",
            "|---|---|---|---|",
            "| " + " | ".join(_cell(c) for c in (f"`{code}`", f"`{level}`", when, remedy)) + " |"]
    out += ["", "## Each shot", "",
            "Every shot is judged as it is processed. A warning marks the shot in the "
            "console and in the run file; the shot stays in the mean, and the operator "
            "decides.", "",
            "| Check | Level | Reported when | Remedy |",
            "|---|---|---|---|"]
    for name, level, when, remedy in SHOT_CHECKS:
        out.append("| " + " | ".join(_cell(c) for c in (name, f"`{level}`", when, remedy)) + " |")
    out.append("")
    return "\n".join(out)


def actions() -> str:
    from bace.service.rigs import ACTION_DOCS

    out = ["# Bench actions", "",
           "Every action the console offers outside a run: the instrument, what it "
           "does, and when the bench refuses it. Each is journaled with the values "
           "before it and followed by a read-back. A refusal states what is in the way.",
           "",
           GENERATED_NOTE.format(source="`ACTION_DOCS` in `bace/service/rigs.py`"), "",
           "| Action | Instrument | Effect | Refused when |",
           "|---|---|---|---|"]
    for name, (instrument, effect, refused) in ACTION_DOCS.items():
        out.append("| " + " | ".join(_cell(c) for c in (
            f"`{name}`", instrument, effect, refused)) + " |")
    out.append("")
    return "\n".join(out)


GENERATED = {"4.1-parameters.md": parameters, "4.2-checks.md": checks,
             "4.3-actions.md": actions}


def stale() -> list[str]:
    """The generated chapters whose file differs from what the code gives."""
    bad = []
    for name, make in GENERATED.items():
        path = os.path.join(MANUAL, name)
        try:
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != make():
            bad.append(name)
    return bad


def write_generated() -> None:
    for name, make in GENERATED.items():
        with open(os.path.join(MANUAL, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(make())


# -- the book -------------------------------------------------------------------------
PARTS = {"1": "I Operation", "2": "II Principle", "3": "III Maintenance", "4": "IV Reference"}
_CHAPTER = re.compile(r"^(\d)\.(\d+)-[\w-]+\.md$")


def chapters() -> list[str]:
    """The chapter files, in reading order."""
    names = [n for n in os.listdir(MANUAL) if _CHAPTER.match(n)]
    return sorted(names, key=lambda n: tuple(int(x) for x in _CHAPTER.match(n).groups()))


def _anchor(stem: str, heading: str = "") -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
    return f"ch-{stem}" + (f"--{slug}" if slug else "")


def _inline(text: str, links: dict[str, str]) -> str:
    """Code spans, emphasis and links; everything else escaped."""
    parts = re.split(r"(`[^`]*`)", text)
    out = []
    for part in parts:
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(f"<code>{html.escape(part[1:-1])}</code>")
            continue
        s = html.escape(part.replace("\\|", "|"), quote=False)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)

        s = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", lambda m: _link(m.group(1), m.group(2), links), s)
        out.append(s)
    # A link's label may be a code span: `[`x`](y)` was split around the span.
    joined = "".join(out)
    return re.sub(r"\[(<code>[^<]*</code>)\]\(([^)]+)\)",
                  lambda m: _link(m.group(1), m.group(2), links), joined)


def _link(label: str, target: str, links: dict[str, str]) -> str:
    """A chapter link goes to its anchor in the book, with its section when it
    names one; a web address stays a link; a file outside the manual is text."""
    file, _, fragment = target.partition("#")
    if file in links:
        anchor = links[file] + (f"--{fragment}" if fragment else "")
        return f'<a href="#{anchor}">{label}</a>'
    if re.match(r"https?://", target):
        return f'<a href="{html.escape(target)}">{label}</a>'
    return label


def figures(text: str) -> list[str]:
    """The image paths of a chapter's figure lines, relative to `docs/manual/`."""
    return re.findall(r"^!\[[^\]]*\]\(([^)\s]+)\)\s*$", text, flags=re.M)


def _figure(caption: str, path: str, links: dict[str, str]) -> str:
    """A figure with its image embedded as a data URL."""
    full = os.path.join(MANUAL, path)
    kind = mimetypes.guess_type(full)[0] or "application/octet-stream"
    with open(full, "rb") as fh:
        data = base64.b64encode(fh.read()).decode("ascii")
    return (f'<figure><img src="data:{kind};base64,{data}" alt="{html.escape(caption)}">'
            f"<figcaption>{_inline(caption, links)}</figcaption></figure>")


def _cells(row: str) -> list[str]:
    row = row.strip()
    if row.startswith("|"):
        row = row[1:]
    if row.endswith("|") and not row.endswith("\\|"):
        row = row[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", row)]


def markdown(text: str, stem: str, links: dict[str, str], number: str) -> str:
    """The manual's Markdown as HTML."""
    lines = text.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    para: list[str] = []
    i = 0

    def flush() -> None:
        if para:
            out.append(f"<p>{_inline(' '.join(para), links)}</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            flush()
            block = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                block.append(lines[i])
                i += 1
            out.append(f"<pre>{html.escape(chr(10).join(block))}</pre>")
            i += 1
            continue
        if line.startswith("    ") and not para:
            block = []
            while i < len(lines) and (lines[i].startswith("    ") or not lines[i].strip()):
                block.append(lines[i][4:])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            out.append(f"<pre>{html.escape(chr(10).join(block))}</pre>")
            continue
        m = re.match(r"^!\[([^\]]*)\]\(([^)\s]+)\)\s*$", line)
        if m:
            flush()
            out.append(_figure(m.group(1), m.group(2), links))
            i += 1
            continue
        m = re.match(r"^(#{1,3}) (.*)$", line)
        if m:
            flush()
            level, title = len(m.group(1)), m.group(2).strip()
            if level == 1:
                out.append(f'<h1 id="{_anchor(stem)}"><span class="num">{number}</span> '
                           f"{_inline(title, links)}</h1>")
            else:
                out.append(f'<h{level} id="{_anchor(stem, title)}">{_inline(title, links)}'
                           f"</h{level}>")
            i += 1
            continue
        if line.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(_cells(lines[i]))
                i += 1
            # A pipe inside a cell is escaped in the source; once the row is
            # split it is a pipe again, in code spans as well.
            rows = [[c.replace("\\|", "|") for c in r] for r in rows]
            head, body = rows[0], [r for r in rows[1:] if not all(re.fullmatch(r":?-+:?", c) for c in r)]
            out.append("<table><thead><tr>" + "".join(f"<th>{_inline(c, links)}</th>" for c in head)
                       + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{_inline(c, links)}</td>" for c in r) + "</tr>"
                                 for r in body)
                       + "</tbody></table>")
            continue
        m = re.match(r"^(\d+\.|-) (.*)$", line)
        if m:
            flush()
            tag = "ol" if m.group(1) != "-" else "ul"
            items = []
            while i < len(lines):
                m = re.match(r"^(\d+\.|-) (.*)$", lines[i])
                if not m:
                    break
                items.append(m.group(2))
                i += 1
                while i < len(lines) and lines[i].startswith("   ") and lines[i].strip():
                    items[-1] += " " + lines[i].strip()
                    i += 1
            out.append(f"<{tag}>" + "".join(f"<li>{_inline(t, links)}</li>" for t in items)
                       + f"</{tag}>")
            continue
        if line.strip() in ("---", ""):
            flush()
            i += 1
            continue
        para.append(line.strip())
        i += 1
    flush()
    return "\n".join(out)


