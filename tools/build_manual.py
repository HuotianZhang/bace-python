def book() -> str:
    names = chapters()
    stems = {n: n[:-3] for n in names}
    links = {n: _anchor(stems[n]) for n in names}
    toc, body, part = [], [], None
    for n in names:
        number = ".".join(_CHAPTER.match(n).groups())
        with open(os.path.join(MANUAL, n), encoding="utf-8") as fh:
            text = fh.read()
        title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), n)
        if number.split(".")[0] != part:
            part = number.split(".")[0]
            toc.append(f'<li class="part">{html.escape(PARTS.get(part, part))}</li>')
        toc.append(f'<li><a href="#{links[n]}"><span class="num">{number}</span>'
                   f"{html.escape(title)}</a></li>")
        chapter = markdown(text, stems[n], links, number)
        chapter = re.sub(r"(<table>.*?</table>)", r'<div class="wrap">\1</div>', chapter,
                         flags=re.S)
        body.append(f'<section class="chapter">{chapter}</section>')
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            "<title>BACE bench manual</title>"
            f"<style>{STYLE}</style></head><body><main>"
            '<div class="title"><h1>BACE bench manual</h1>'
            "<p>Operation, principle, maintenance and reference for the bias-assisted "
            "charge extraction bench.</p></div>"
            f'<nav><h2>Contents</h2><ol>{"".join(toc)}</ol></nav>'
            + "".join(body) + "</main></body></html>\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if a generated chapter is out of date")
    ap.add_argument("--book", nargs="?", const=BOOK, default=None, metavar="PATH",
                    help=f"also write the book (default {os.path.relpath(BOOK, ROOT)})")
    a = ap.parse_args(argv)
    if a.check:
        bad = stale()
        for name in bad:
            print(f"{name} is out of date: run python tools/build_manual.py")
        return 1 if bad else 0
    write_generated()
    print("wrote " + ", ".join(GENERATED))
    if a.book:
        os.makedirs(os.path.dirname(os.path.abspath(a.book)), exist_ok=True)
        with open(a.book, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(book())
        print(f"wrote {a.book}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
